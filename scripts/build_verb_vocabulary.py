"""Build bundled verb constants from downloaded linguistic sources (development only).
Input cache names and provenance are documented in docs/VERB-VOCABULARY.md.
This script does not download files or run application checks.
"""
import argparse
import ast
import hashlib
import json
import re
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def normalized(value):
    value = unicodedata.normalize('NFC', value.strip().lower())
    value = re.sub(r'[-_\s]+', '', value)
    ascii_value = ''.join(c for c in unicodedata.normalize('NFKD', value) if not unicodedata.combining(c))
    return value if re.fullmatch('[a-z]+', ascii_value) else ''


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--source-dir', type=Path, default=ROOT / '.tooling/vocabulary')
    args = parser.parse_args()
    cache = args.source_dir
    pools = {}
    pools['en'] = [line.split()[0] for line in (cache/'en-index').read_text(encoding='ascii').splitlines()
                   if line and not line[0].isspace()]
    for lang in ('pt', 'es'):
        files = sorted(cache.glob(lang+'-*.json'))
        expected = json.loads((cache/(lang+'-categories')).read_bytes())
        if len(files) != len(expected): raise SystemExit('Missing category data: '+lang)
        pools[lang] = [word for file in files for word in json.loads(file.read_bytes())]
    raw = (cache/'pt-verbs').read_bytes()
    try: portuguese = raw.decode('utf-8')
    except UnicodeDecodeError: portuguese = raw.decode('latin-1')
    pools['pt'] += portuguese.splitlines()
    # Keep the original words and normalize duplicates exactly as username generation does.
    tree = ast.parse((ROOT/'words.py').read_text(encoding='utf-8'))
    original = {}
    for node in tree.body:
        if isinstance(node, ast.Assign) and isinstance(node.value, ast.Call) and isinstance(node.value.func, ast.Attribute):
            if node.value.func.attr == 'split' and isinstance(node.value.func.value, ast.Constant):
                for name in node.targets:
                    if isinstance(name, ast.Name) and name.id.startswith('VERBS_'):
                        original[name.id[-2:].lower()] = node.value.func.value.value.split()
    content = ['"""Bundled verb vocabulary. See ui/third-party-vocabulary.txt for attribution and licenses.\n'
               'Generated by scripts/build_verb_vocabulary.py. No runtime downloads.\n'
               'PT/ES derivative data: CC BY-SA 3.0. EN data: WordNet license.\n"""\n']
    counts = {}
    for lang in ('en', 'pt', 'es'):
        words = {}
        for rawword in original.get(lang, []) + pools[lang]:
            word = normalized(rawword)
            if word:
                key = ''.join(c for c in unicodedata.normalize('NFKD',word) if not unicodedata.combining(c))
                words.setdefault(key, word)
        values = sorted(words.values()); counts[lang] = len(values)
        lines = [' '.join(values[i:i+10]) for i in range(0,len(values),10)]
        content.append('VERBS_'+lang.upper()+' = """\n'+'\n'.join(lines)+'\n""".split()\n')
    content.append('VERB_COUNTS = '+repr(counts)+'\n')
    (ROOT/'verb_vocabulary.py').write_text('\n'.join(content),encoding='utf-8')
    sources = [file for file in cache.iterdir() if file.name in {'en-index','en-license','pt-verbs','pt-license','ian-readme'} or re.fullmatch('(pt|es)-.+\\.json',file.name)]
    manifest = '\n'.join(hashlib.sha256(f.read_bytes()).hexdigest()+'  '+f.name for f in sorted(sources))
    (ROOT/'docs/VERB-SOURCE-SHA256.txt').write_text(manifest+'\n',encoding='utf-8')
    print(counts)


if __name__ == '__main__': main()
